CREATE DATABASE IF NOT EXISTS china_travel
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

USE china_travel;

-- ----------------------------------------------------------
-- ตาราง users : เก็บข้อมูลสมาชิกสำหรับสมัคร/เข้าสู่ระบบ
-- ----------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    id            INT AUTO_INCREMENT PRIMARY KEY,
    full_name     VARCHAR(100)  NOT NULL,
    username      VARCHAR(50)   NOT NULL UNIQUE,
    email         VARCHAR(100)  NOT NULL UNIQUE,
    password      VARCHAR(255)  NOT NULL,   -- เก็บด้วย password_hash() ห้ามเก็บ plain text
    created_at    DATETIME      DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- ----------------------------------------------------------
-- ตาราง destinations : ข้อมูลสถานที่ท่องเที่ยวในประเทศจีน
-- ----------------------------------------------------------
CREATE TABLE IF NOT EXISTS destinations (
    id            INT AUTO_INCREMENT PRIMARY KEY,
    name_th       VARCHAR(150)  NOT NULL,   -- ชื่อภาษาไทย
    name_cn       VARCHAR(150)  NOT NULL,   -- ชื่อภาษาจีน
    city          VARCHAR(100)  NOT NULL,
    category      VARCHAR(50)   NOT NULL,   -- เช่น ประวัติศาสตร์, ธรรมชาติ, เมือง
    description   TEXT          NOT NULL,
    image_file    VARCHAR(255)  NOT NULL,   -- ชื่อไฟล์รูปใน assets/images
    best_season   VARCHAR(100),
    rating        DECIMAL(2,1)  DEFAULT 4.5,
    created_at    DATETIME      DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

